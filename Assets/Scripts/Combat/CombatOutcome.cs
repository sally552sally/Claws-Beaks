/// <summary>
/// Чем закончился бой для нас.
///
/// Раньше исход был булевым (DidWin), и любой не-выигрыш считался поражением. Прерванный бой
/// (сервер завершает сессию по истечении CombatConfig.MaxSessionMinutes, либо по таймеру копии
/// в данже) приходит без победившей стороны — и живой персонаж с полным HP видел «Поражение...».
/// Трёх состояний ровно столько, сколько их у сервера: combat_state = active/finished/interrupted,
/// плюс у finished есть winner_side, которого у interrupted нет.
/// </summary>
public enum CombatOutcome
{
    /// <summary>Бой не завершён.</summary>
    None = 0,

    /// <summary>Победила наша сторона.</summary>
    Win,

    /// <summary>Победила сторона противника (или мы погибли).</summary>
    Loss,

    /// <summary>
    /// Бой прерван без победителя — истёк лимит длительности сессии или прерван бой в данже.
    /// Это не поражение: HP сохраняется, персонаж остаётся жив и на месте, воскрешение не нужно.
    /// </summary>
    Interrupted
}
